/**
 * УНИВЕРСАЛЬНАЯ ВАЛИДАЦИЯ ЗАПРОСОВ
 * Эта функция принимает "схему" (правила) и возвращает Middleware.
 */
export const validateRequest = (schema) => {
  // Возвращаем стандартную функцию Express (req, res, next)
  return (req, res, next) => {
    
    // ШАГ 1: Запускаем проверку.
    // safeParse не выбрасывает ошибку (не "крашит" сервер), 
    // а возвращает объект с результатом: либо успех, либо список ошибок.
    const result = schema.safeParse(req.body);

    // ШАГ 2: Если данные НЕ прошли проверку
    if (!result.success) {
      
      // ШАГ 3: Форматируем ошибки.
      // Zod выдает сложный объект ошибок. .format() превращает его в более читаемую структуру.
      const formatted = result.error.format();

      // ШАГ 4: "Распаковка" ошибок (Flattening).
      // Здесь происходит магия превращения сложного объекта во фронтенд-дружелюбную строку.
      const flatErrors = Object.values(formatted)
        .flat()           // Делаем массив плоским
        .filter(Boolean)  // Убираем пустые значения
        .map((err) => err._errors) // Достаем только тексты самих ошибок
        .flat();          // Снова делаем массив плоским, чтобы получить массив строк

      // ШАГ 5: Отправка ответа клиенту.
      // Мы объединяем все ошибки в одну строку через запятую (например: "Email is required, Password too short")
      return res.status(400).json({ message: flatErrors.join(", ") });
    }

    // ШАГ 6: Если данные верны — пропускаем запрос дальше к контроллеру
    next();
  };
};